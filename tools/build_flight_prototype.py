import unreal
P = '/Game/DragonRider'
assets = unreal.AssetToolsHelpers.get_asset_tools()
for name in ['BP_FlightPrototype', 'BP_FlightPrototypeMode', 'Lvl_FlightPrototype']:
    if unreal.EditorAssetLibrary.does_asset_exist(P + '/' + name):
        raise RuntimeError('Preserving existing asset: ' + name)
factory = unreal.BlueprintFactory()
factory.set_editor_property('parent_class', unreal.DefaultPawn)
bp = assets.create_asset('BP_FlightPrototype', P, unreal.Blueprint, factory)
sub = unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)
lib = unreal.SubobjectDataBlueprintFunctionLibrary
handles = sub.k2_gather_subobject_data_for_blueprint(bp)
def add(parent, cls, name):
    handle, reason = sub.add_new_subobject(unreal.AddNewSubobjectParams(parent_handle=parent, new_class=cls, blueprint_context=bp))
    if not lib.is_valid(lib.get_data(handle)):
        raise RuntimeError(str(reason))
    sub.rename_subobject(handle, unreal.Text(name))
    obj = lib.get_object_for_blueprint(lib.get_data(handle), bp)
    return handle, obj
boom_h, boom = add(handles[0], unreal.SpringArmComponent, 'FlightCameraBoom')
boom.set_editor_property('target_arm_length', 650.0)
boom.set_editor_property('socket_offset', unreal.Vector(0, 0, 120))
boom.set_editor_property('use_pawn_control_rotation', True)
boom.set_editor_property('enable_camera_lag', True)
boom.set_editor_property('camera_lag_speed', 7.0)
cam_h, cam = add(boom_h, unreal.CameraComponent, 'FlightCamera')
cam.set_editor_property('field_of_view', 85.0)
unreal.BlueprintEditorLibrary.compile_blueprint(bp)
cdo = unreal.get_default_object(bp.generated_class())
movement = cdo.get_movement_component()
movement.set_editor_property('max_speed', 2400.0)
movement.set_editor_property('acceleration', 1400.0)
movement.set_editor_property('deceleration', 950.0)
movement.set_editor_property('turning_boost', 2.0)
cdo.get_editor_property('mesh_component').set_editor_property('owner_no_see', False)
unreal.EditorAssetLibrary.save_loaded_asset(bp)
factory = unreal.BlueprintFactory()
factory.set_editor_property('parent_class', unreal.GameModeBase)
mode = assets.create_asset('BP_FlightPrototypeMode', P, unreal.Blueprint, factory)
unreal.BlueprintEditorLibrary.compile_blueprint(mode)
unreal.get_default_object(mode.generated_class()).set_editor_property('default_pawn_class', bp.generated_class())
unreal.EditorAssetLibrary.save_loaded_asset(mode)
level = unreal.EditorAssetLibrary.duplicate_asset(P + '/Lvl_FlightPass', P + '/Lvl_FlightPrototype')
if not level: raise RuntimeError('Level duplicate failed')
levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
if not levels.load_level(P + '/Lvl_FlightPrototype'): raise RuntimeError('Level load failed')
world = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).get_editor_world()
world.get_world_settings().set_editor_property('default_game_mode', mode.generated_class())
if not levels.save_current_level(): raise RuntimeError('Level save failed')
unreal.log('FLIGHT_PROTOTYPE_SAVED')
